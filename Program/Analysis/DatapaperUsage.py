#!/usr/bin/env python3
"""Usage example: link a panel to its long table and source files, then count
how limits moved between two editions.

Every panel carries ``source_record_ids_YYYY``, a JSON array of the long-table
records behind each edition cell. Exploding those arrays joins a panel cell to
its printed rule, and the rule's ``extraction_source_id`` joins it to
``source_manifest.csv``. The same pattern works for every panel; the example
uses the contaminant member panel.

The count classifies members printed in two editions as tightened, relaxed,
unchanged or incomparable. The release's ``trend`` field already applies the
comparability gates (unit dimension, basis, scope, edition gaps), so a row
whose trend starts with ``incomparable_`` is not compared. The counts show the
method only and are not a finding about regulatory stringency.

Only pandas is needed. Point ``--release-dir`` at a downloaded copy of the
package; inside the workspace the counts are also written as LaTeX macros to
``Results/tab/DatapaperUsageNumbers.tex``.
"""
import argparse
import json
from pathlib import Path

import pandas as pd

PROJ = Path(__file__).resolve().parents[2]
RELEASE = PROJ / "Data" / "Final" / "china_food_limit_panel_v1"
MACROS = PROJ / "Results" / "tab" / "DatapaperUsageNumbers.tex"
# Mass-per-mass units convert to mg/kg; mg/L has no mass equivalent without a density.
TO_MG_PER_KG = {"mg/kg": 1.0, "μg/kg": 0.001}


def read(release, name):
    # Identifiers and codes are text, and a blank field stays blank.
    return pd.read_csv(release / name, dtype=str, keep_default_na=False, encoding="utf-8-sig")


def link_cells(panel, long, manifest):
    """One row per panel cell and contributing long-table record, with its source file."""
    lineage = [c for c in panel if c.startswith("source_record_ids_")]
    links = (panel.melt(id_vars="record_id", value_vars=lineage,
                        var_name="edition", value_name="ids")
             .assign(edition=lambda d: d["edition"].str[-4:],
                     long_id=lambda d: d["ids"].map(json.loads))
             .explode("long_id")
             .dropna(subset=["long_id"])
             .drop(columns="ids"))
    cells = (links.merge(long, left_on="long_id", right_on="record_id",
                         suffixes=("_panel", ""), validate="many_to_one")
             .merge(manifest[["source_id", "source_filename", "sha256"]],
                    left_on="extraction_source_id", right_on="source_id",
                    validate="many_to_one"))
    assert len(cells) == len(links), "a lineage identifier did not resolve"
    return cells


def value(rows, year):
    unit = rows[f"unit_{year}"]
    return rows[f"v{year}"].astype(float) * unit.map(TO_MG_PER_KG).fillna(1.0)


def pair_counts(panel, before, after):
    both = panel[(panel[f"v{before}"] != "") & (panel[f"v{after}"] != "")]
    comparable = both[~both["trend"].str.startswith("incomparable_")]
    # The trend gate already rules out mg/L against mg/kg.
    assert ((comparable[f"unit_{before}"] == "mg/L")
            == (comparable[f"unit_{after}"] == "mg/L")).all()
    old, new = value(comparable, before), value(comparable, after)
    changed = comparable[old != new]
    return {
        "both": len(both),
        "incomparable": len(both) - len(comparable),
        "tightened": int((new < old).sum()),
        "relaxed": int((new > old).sum()),
        "unchanged": int((new == old).sum()),
        "host changed": int((changed[f"host_category_{before}"]
                             != changed[f"host_category_{after}"]).sum()),
    }


def write_macros(path, numbers):
    lines = ["% Generated by Program/Analysis/DatapaperUsage.py; do not edit."]
    lines += [f"\\newcommand{{\\{name}}}{{{n:,}}}" for name, n in numbers.items()]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {path}")


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--release-dir", type=Path, default=RELEASE)
    parser.add_argument("--before", default="2017")
    parser.add_argument("--after", default="2022")
    parser.add_argument("--macros", type=Path, default=MACROS,
                        help="LaTeX macro file; written only when its directory exists")
    return parser.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)
    panel = read(args.release_dir, "pollutant_member_panel.csv")
    cells = link_cells(panel,
                       read(args.release_dir, "pollutant_limits_long.csv"),
                       read(args.release_dir, "source_manifest.csv"))
    filled = sum((panel[c] != "").sum() for c in panel if c[1:].isdigit())
    assert len(cells) == filled, "a populated cell has no long-table record"
    print(f"{len(cells):,} panel cells -> {cells['long_id'].nunique():,} long-table records "
          f"-> {cells['source_filename'].nunique()} source files")

    counts = pair_counts(panel, args.before, args.after)
    print(f"members in both {args.before} and {args.after}: {counts['both']}")
    for label in ("tightened", "relaxed", "unchanged", "incomparable"):
        print(f"  {label:<13}{counts[label]:>5}")
    print(f"  of the changed, host category differs: {counts['host changed']}")

    if args.macros.parent.is_dir():
        write_macros(args.macros, {
            "UsageLinkedCells": len(cells),
            "UsageLinkedRecords": cells["long_id"].nunique(),
            "UsageLinkedSources": cells["source_filename"].nunique(),
            "UsagePairBoth": counts["both"],
            "UsagePairTightened": counts["tightened"],
            "UsagePairRelaxed": counts["relaxed"],
            "UsagePairUnchanged": counts["unchanged"],
            "UsagePairIncomparable": counts["incomparable"],
            "UsagePairHostChanged": counts["host changed"],
        })


if __name__ == "__main__":
    main()
